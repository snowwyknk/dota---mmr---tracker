CREATE TABLE IF NOT EXISTS hero_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steam_id VARCHAR(17) NOT NULL REFERENCES profiles (steam_id) ON DELETE CASCADE,
    hero_key VARCHAR(50) NOT NULL,
    hero_name VARCHAR(50) NOT NULL,
    hero_level SMALLINT NOT NULL CHECK (hero_level BETWEEN 0 AND 30),
    current_xp INTEGER NOT NULL CHECK (current_xp >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (steam_id, hero_key)
);
